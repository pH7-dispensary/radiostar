import assert from "node:assert/strict";
import { createEncounterPrewarmer } from "./native/src/intelligenceEncounters.mjs";
let now = 1000, calls = [];
const episodes = Array.from({ length: 10 }, (_, index) => ({ id: String(index), feedUrl: "https://publisher.example/feed" }));
const warm = createEncounterPrewarmer(async (...input) => { calls.push(input); }, { now: () => now });
await warm(episodes, false); assert.equal(calls.length, 0);
await warm(episodes, true, "saved"); assert.equal(calls.length, 3);
assert.equal(calls[0][2], "saved");
await warm(episodes); assert.equal(calls.length, 3);
now += 300001; await warm(episodes); assert.equal(calls.length, 6);
let attempts = 0;
const offline = createEncounterPrewarmer(async () => { attempts++; throw Error("offline"); });
await offline([episodes[0]]); await offline([episodes[0]]); assert.equal(attempts, 2);
const releases = []; let active = 0, peak = 0;
const gated = createEncounterPrewarmer(async () => { active++; peak = Math.max(peak, active); await new Promise((resolve) => { releases.push(resolve); }); active--; });
const pending = gated([episodes[0]]); const second = gated([episodes[1]]);
await gated(episodes.slice(2)); assert.equal(peak, 2);
releases.forEach((resolve) => resolve()); await Promise.all([pending, second]);
console.log("Native encounters respect opt-out, three-episode scope, deduplication, cooldown, concurrency and offline saves.");
