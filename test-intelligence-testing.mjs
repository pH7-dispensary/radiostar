import assert from "node:assert/strict";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { LocalStore } from "./persistence.mjs";
import { IntelligenceTestMode } from "./intelligence-test-mode.mjs";
import { BudgetLedger, generateLongFormIntelligence } from "./openai-intelligence.mjs";
import { transcribeOnDemand } from "./transcription.mjs";
import { ProcessingQueue } from "./processing-queue.mjs";
import { createStarCastServer } from "./server.mjs";
import { createHash } from "node:crypto";

const directory = await mkdtemp(join(tmpdir(), "starcast-testing-"));
const path = join(directory, "store.sqlite");
let store = new LocalStore(path);
let now = Date.now();
const listenerId = "existing-internal-listener";
const pilotToken = "internal-test-pilot-token-with-at-least-32-bytes";
store.set("installation", "credential", { id: listenerId });
store.set("pilot-device", createHash("sha256").update(pilotToken).digest("hex"), { listenerId, expiresAt: new Date(now + 30 * 86400000).toISOString() });
let mode = new IntelligenceTestMode(store, { now: () => now });
const config = mode.set({ enabled: true, expectedVersion: 0, listenerIds: [listenerId], reason: "Authorised bounded testing", confirmation: "ENABLE TESTING" }, "test-super-admin");
assert.equal(Date.parse(config.expiresAt) - now, 7 * 86400000);
assert.equal(mode.allowed("arbitrary-listener"), false);
assert.throws(() => mode.set({ enabled: true, expectedVersion: 0 }, "admin"), /changed/);
assert.throws(() => mode.set({ enabled: true, expectedVersion: 1, reason: "x", confirmation: "ENABLE TESTING", listenerIds: ["new-stranger"] }, "admin"), /enrolled/);
let ledger = new BudgetLedger({ enabled: true }, store, () => mode.limits({ listenerId, version: 1 }));
ledger.reserve({ id: "raised", usd: 6 }); ledger.reconcile("raised", { usd: 6 });
assert.throws(() => new BudgetLedger({ enabled: true }, store).reserve({ id: "ordinary", usd: 0.1 }), /budget/);
now += 8 * 86400000;
assert.equal(ledger.controls.dailyUsd, 5);
assert.throws(() => ledger.reserve({ id: "expired", usd: 0.1 }), /budget/);
now -= 8 * 86400000;

let audioCalls = 0, interrupt = true;
const audioClient = { audio: { transcriptions: { create: async () => { audioCalls++; return { segments: [{ start: 0, end: 10, text: "This original owned fixture describes reliable podcast intelligence and evidence based decisions, with careful source attribution and cost accounting." }] }; } } } };
const audioOptions = () => ({ episodeId: "owned", audioUrl: "https://publisher.example/owned.mp3", durationMs: 14_400_000, chunkFactory: async (part) => { if (part.index === 2 && interrupt) throw Error("Local worker interruption before provider call"); return Buffer.from("mock"); }, client: audioClient, ledger, requestId: "audio-test", authorised: true, checkpointStore: store, checkpointPrefix: "owned:exact-source-byte-hash" });
await assert.rejects(transcribeOnDemand(audioOptions()), /interruption/);
assert.equal(audioCalls, 2);
store.close(); store = new LocalStore(path); mode = new IntelligenceTestMode(store, { now: () => now });
ledger = new BudgetLedger({ enabled: true }, store, () => mode.limits({ listenerId, version: 1 }));
interrupt = false;
const transcript = await transcribeOnDemand(audioOptions());
assert.equal(audioCalls, 13, "completed paid chunks survive SQLite reopening without replay");
assert.equal(transcript.durationMs, 14_400_000);
assert(transcript.segments.at(-1).startMs > 3 * 3600000);
assert.equal(store.all("transcription-checkpoint").length, 13);
await transcribeOnDemand(audioOptions()); assert.equal(audioCalls, 13);
let unknownCalls = 0;
const unknown = { ...audioOptions(), checkpointPrefix: "unknown:source", durationMs: 60_000, client: { audio: { transcriptions: { create: async () => { unknownCalls++; throw Error("socket lost after send"); } } } } };
await assert.rejects(transcribeOnDemand(unknown), (error) => error.code === "PROVIDER_OUTCOME_UNKNOWN");
await assert.rejects(transcribeOnDemand(unknown), (error) => error.code === "PROVIDER_OUTCOME_UNKNOWN");
assert.equal(unknownCalls, 1);
let retain = true;
await assert.rejects(transcribeOnDemand({ ...audioOptions(), durationMs: 60_000, checkpointPrefix: "removed:source", canPersist: () => retain, client: { audio: { transcriptions: { create: async () => { retain = false; return { segments: [{ start: 0, end: 10, text: "Response delivered after a rights-holder removal." }] }; } } } } }), /Rights permission/);
assert.equal(store.all("transcription-checkpoint").some(([key]) => key.startsWith("removed:")), false, "late responses cannot resurrect removed transcript checkpoints");

let textCalls = 0, stopAfterMap = true;
const textClient = { responses: { create: async ({ input }) => {
  textCalls++; const count = input[1].content.split("\n").filter((line) => /^source \d+/.test(line)).length;
  return { status: "completed", output_text: JSON.stringify({ overview: "Reliable podcast intelligence uses source evidence and careful attribution.", themes: ["Evidence"], detail: "Reliable podcast intelligence uses source evidence and careful attribution.", sourceSegmentIndexes: [1], chapters: [{ title: "Evidence", description: "Reliable podcast intelligence uses source evidence and careful attribution.", sourceSegmentIndexes: [1, count] }] }), usage: { input_tokens: 100, output_tokens: 100 } };
} } };
const long = { ...transcript, segments: Array.from({ length: 800 }, (_, index) => ({ id: `source-${index}`, startMs: index * 18000, endMs: (index + 1) * 18000, text: "Reliable podcast intelligence uses source evidence and careful attribution. ".repeat(15) })) };
const textOptions = () => ({ transcript: long, ledger, requestId: "long-text", client: textClient, checkpointStore: store, checkpointPrefix: "owned", onProgress: ({ completedBatches }) => { if (completedBatches === 2 && stopAfterMap) throw Error("worker stopped between batches"); } });
await assert.rejects(generateLongFormIntelligence(textOptions()), /between batches/);
assert.equal(textCalls, 2);
stopAfterMap = false;
const result = await generateLongFormIntelligence(textOptions());
const paidTextCalls = textCalls;
assert(result.brief.sourceSegmentIds.every((id) => id.startsWith("source-")));
assert(result.chapters.length > 10);
assert(result.chapters.at(-1).endMs <= long.durationMs);
await generateLongFormIntelligence(textOptions()); assert.equal(textCalls, paidTextCalls);
assert.equal(ledger.reservations.size, 0);
await assert.rejects(generateLongFormIntelligence({ ...textOptions(), requestId: "removed-analysis", checkpointPrefix: "removed-analysis", canPersist: () => false }), /Rights permission/);
assert.equal(store.all("analysis-checkpoint").some(([key]) => key.startsWith("removed-analysis:")), false);

let renewals = 0, acknowledgements = 0;
const queue = new ProcessingQueue({ queueUrl: "https://sqs.eu-west-2.amazonaws.com/208096650030/starcast-phase1-processing", renewalMs: 5, client: { send: async (command) => {
  if (command.constructor.name === "ReceiveMessageCommand") return { Messages: [{ Body: "{}", ReceiptHandle: "receipt" }] };
  if (command.constructor.name === "ChangeMessageVisibilityCommand") renewals++;
  if (command.constructor.name === "DeleteMessageCommand") acknowledgements++;
  return {};
} } });
await queue.run({ recover: async () => {}, execute: async () => { await new Promise((resolve) => setTimeout(resolve, 25)); queue.stop(); } });
assert(renewals >= 1); assert.equal(acknowledgements, 1);

const app = createStarCastServer({ store, env: { STARCAST_ADMIN_TOKEN: "test-admin", STARCAST_DEV_INTELLIGENCE_TOKEN: "dev-test" } });
await new Promise((resolve) => app.server.listen(0, "127.0.0.1", resolve));
const origin = `http://127.0.0.1:${app.server.address().port}`;
assert.equal((await fetch(origin + "/api/admin/intelligence/testing")).status, 403);
const adminHeaders = { "x-star-cast-admin-token": "test-admin", "x-star-cast-dev-token": "dev-test", "content-type": "application/json" };
const status = await fetch(origin + "/api/admin/intelligence/testing", { headers: adminHeaders });
assert.equal(status.status, 200);
const readOnly = app.adminService.startSession({ id: "reader", role: "READ_ONLY", name: "Reader" });
assert.equal((await fetch(origin + "/api/admin/intelligence/testing", { method: "POST", headers: { "content-type": "application/json", cookie: `starcast_admin=${readOnly.id}`, "x-star-cast-csrf": readOnly.csrf }, body: JSON.stringify({ enabled: false }) })).status, 403);
const superSession = app.adminService.startSession({ id: "super", role: "SUPER_ADMIN", name: "Super" });
assert.equal((await fetch(origin + "/api/admin/intelligence/testing", { method: "POST", headers: { "content-type": "application/json", cookie: `starcast_admin=${superSession.id}` }, body: JSON.stringify({ enabled: false }) })).status, 403, "CSRF required");
const disabled = await fetch(origin + "/api/admin/intelligence/testing", { method: "POST", headers: adminHeaders, body: JSON.stringify({ enabled: false, expectedVersion: 1, reason: "End test", confirmation: "DISABLE TESTING" }) });
assert.equal(disabled.status, 200);
assert.equal(mode.allowed(listenerId), false);
assert.equal(store.all("transcription-checkpoint").length, 14, "disable preserves cached work");
await new Promise((resolve) => app.server.close(resolve)); store.close();
await rm(directory, { recursive: true, force: true });
console.log("Internal tester limits, expiry, durable four-hour chunks, hierarchical checkpoint recovery, unknown-outcome safety, lease renewal and admin access passed.");
