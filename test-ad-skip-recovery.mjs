const sha = bytes => createHash("sha256").update(new Uint8Array(bytes)).digest("hex");
const bytes = new Uint8Array(65536).fill(42);
const variant = { deliveryUrl: "https://publisher.example/audio", etag: '"exact"', contentLength: 250000000, audioVariantFingerprint: "a".repeat(64), windows: [{start: 150000000, end: 150065535, sha256: sha(bytes)}] };
let transferred = 0;
const fetcher = async (_url, options) => {
  if (options.headers["If-Match"] !== variant.etag) return new Response(null, {status: 412});
  transferred += bytes.length;
  return new Response(bytes, {status: 206, headers: {etag: variant.etag, "content-range": "bytes 150000000-150065535/250000000", "content-length": String(bytes.length)}});
};
const proof = await verifyAudioRanges(variant, {fetcher, digest: async bytes => sha(bytes), nonce: "test"});
assert.equal(proof.headers["If-Match"], variant.etag);
assert.equal(transferred, 65536, "250MB source verifies with 64KB, not a full download");
await assert.rejects(verifyAudioRanges(variant, {fetcher: async () => new Response(null, {status: 200}), digest: sha, nonce: "test"}), /PRECONDITION_UNSUPPORTED/);
await assert.rejects(verifyAudioRanges({...variant, windows: [{...variant.windows[0], sha256: "0".repeat(64)}]}, {fetcher, digest: sha, nonce: "test"}), /WITNESS_MISMATCH/);
await assert.rejects(verifyAudioRanges(variant, {fetcher: async (url, options) => options.headers["If-Match"] !== variant.etag ? new Response(null, {status: 412}) : new Response(new Uint8Array(65537), {status: 206, headers: {etag: variant.etag, "content-range": "bytes 150000000-150065535/250000000"}}), digest: sha, nonce: "test"}), /RANGE_SIZE_MISMATCH/);
const interval = {id: "ad", startMs: 10000, endMs: 30000};
let seekCalls = 0;
await assert.rejects(executeVerifiedSkip({interval, positionMs: 29000, durationMs: 60000, current: () => true, getPosition: () => 31000, authorise: async () => ({...interval, targetMs: 30000, expiresAt: Date.now()+10000}), seek: async () => { seekCalls++; return 30000; }}), /left the advert/);
assert.equal(seekCalls, 0, "network latency must not rewind past an advert");
for (const speed of [1, 1.5, 2]) {
  const stages = [];
  const result = await executeVerifiedSkip({interval, positionMs: 15000, durationMs: 60000, current: () => true, getPosition: () => 15000 + 100 * speed, onStage: stage => stages.push(stage), authorise: async () => ({...interval, targetMs: 30000, expiresAt: Date.now()+10000}), seek: async target => target});
  assert.equal(result.durationMs, 15000 - 100*speed);
  assert.equal(await result.undo(), 15000);
  assert.deepEqual(stages, ["seek_attempted"]);
}
const store = new LocalStore(":memory:"), feed = "https://publisher.example/feed", episode = "one", key = episodeKey(feed, episode);
let job = {state: "FAILED", code: "PROCESSING_TIMEOUT", episode: {feedUrl: feed, id: episode, audioUrl: variant.deliveryUrl}};
store.set("intelligence", key, job);
const service = new SkipService(store, {status: () => job});
assert.equal(service.inspect(feed, episode).state, "FAILED");
assert.equal(service.operations().diagnostics[0].candidates, null, "missing analysis is not zero advertisements");
job = {...job, transcript: {audioVariant: "v1", transcriptVersion: "v1", segments: [{id: "one", startMs: 10000, endMs: 30000, text: "Our sponsor is Example. Use code SAVE for a free trial."}]}};
store.set("intelligence", key, job);
const analysed = service.inspect(feed, episode);
assert.equal(analysed.candidateCount, 1, "failed summaries do not prevent transcript detection");
assert.equal(service.operations().diagnostics[0].analysis, "COMPLETE");
assert.equal(service.operations().diagnostics[0].successes, 0);
store.close();
