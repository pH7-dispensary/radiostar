import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import { createReviewFixture } from "../test-phase3-fixture.mjs";
const { chromium } = await import(process.env.RADIOSTAR_PLAYWRIGHT_MODULE || "playwright");
const { app } = createReviewFixture();
app.store.set("installation", "browser-test", { id: "enrolled-browser-fixture" });
app.store.set("pilot-device", "browser-test", { listenerId: "enrolled-browser-fixture", expiresAt: new Date(Date.now() + 10 * 86400000).toISOString() });
await new Promise((resolve) => app.server.listen(0, "127.0.0.1", resolve));
const origin = `http://127.0.0.1:${app.server.address().port}`;
const output = ".starcast/internal-testing-visual";
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.route("**/*", (route) => new URL(route.request().url()).origin === origin ? route.continue() : route.abort());
  const page = await context.newPage(), errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto(origin + "/admin");
  await page.getByLabel("Administrator credential").fill("phase3-test-admin");
  await page.getByRole("button", { name: "Sign in securely" }).click();
  await page.getByRole("button", { name: "Internal testing", exact: true }).click();
  await page.waitForTimeout(500);
  if (!await page.locator("#testing-controls").count()) throw Error(JSON.stringify({ errors, text: await page.locator("body").innerText() }));
  const form = page.locator("#testing-controls");
  await form.locator('select[name="enabled"]').selectOption("true");
  await form.locator('input[name="listenerIds"]').check();
  await form.locator('input[name="adSkipPilotEnabled"]').check();
  await form.getByLabel("Reason", { exact: true }).fill("Verify internal testing controls with mocked providers.");
  await form.getByLabel("Confirmation", { exact: true }).fill("ENABLE TESTING");
  await form.getByRole("button").click();
  await page.getByText("Testing configuration saved and audited.").waitFor();
  assert.equal(app.store.get("intelligence-test-mode", "configuration").enabled, true);
  assert.equal(app.store.get("intelligence-test-mode", "configuration").adSkipPilotEnabled, true);
  await page.screenshot({ path: output + "/desktop.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
  await page.screenshot({ path: output + "/mobile.png", fullPage: true });
  await form.locator('select[name="enabled"]').selectOption("false");
  await form.getByLabel("Reason", { exact: true }).fill("End bounded browser verification.");
  await form.getByLabel("Confirmation", { exact: true }).fill("DISABLE TESTING");
  await form.getByRole("button").click();
  await page.waitForFunction(() => document.querySelector('#testing-controls select')?.value === 'false' && document.querySelector('#testing-controls input[name="reason"]')?.value === "");
  assert.equal(app.store.get("intelligence-test-mode", "configuration").enabled, false);
  assert.deepEqual(errors, []);
  console.log("Desktop/mobile admin testing enable, expiry display, confirmation, immediate disable and overflow checks passed.");
} finally { await browser.close(); await new Promise((resolve) => app.server.close(resolve)); app.store.close(); }
