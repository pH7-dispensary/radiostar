import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import { createReviewFixture, feedUrl } from "../test-phase3-fixture.mjs";
const { chromium } = await import(process.env.RADIOSTAR_PLAYWRIGHT_MODULE || "playwright");
const { app, providerCalls } = createReviewFixture();
await new Promise((resolve) => app.server.listen(0, "127.0.0.1", resolve));
const origin = `http://127.0.0.1:${app.server.address().port}`;
const output = ".starcast/phase3-visual";
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.route("**/*", (route) => new URL(route.request().url()).origin === origin ? route.continue() : route.abort());
  const page = await context.newPage(), errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto(origin + "/admin");
  await page.getByLabel("Administrator credential").fill("phase3-test-admin");
  await page.getByRole("button", { name: "Sign in securely" }).click();
  await page.getByRole("button", { name: "Podcasts", exact: true }).click();
  await page.getByRole("button", { name: "Open podcast", exact: true }).click();
  const workspace = page.locator("#rights-workspace");
  await workspace.getByRole("heading", { name: "No assessment completed" }).waitFor();
  await workspace.scrollIntoViewIfNeeded();
  await page.screenshot({ path: `${output}/desktop-evidence.png` });
  await workspace.getByText("Review or correct this assessment", { exact: true }).click();
  const form = page.locator("#assessment-form");
  await form.getByLabel("Processing basis", { exact: true }).selectOption("OWNED");
  await form.getByLabel("Evidence reference", { exact: true }).fill("fixture:original-owned-research-v1");
  await form.getByLabel("Rights-holder / independent reviewer", { exact: true }).fill("Radio Star fixture owner");
  await form.getByLabel("Approved basis and its limits", { exact: true }).fill("Original fixture text for bounded software verification.");
  await form.getByLabel("Reason for this decision", { exact: true }).fill("Verify the actual administrative review workflow.");
  await form.getByLabel(/I have reviewed evidence/).check();
  await form.getByLabel("Evidence also covers future eligible episodes", { exact: true }).check();
  await form.getByRole("button", { name: "Preview approval & processing" }).click();
  await page.getByRole("heading", { name: "Approval outcome", exact: true }).waitFor();
  assert.equal(providerCalls(), 0);
  await page.locator("#assessment-preview").scrollIntoViewIfNeeded();
  await page.screenshot({ path: `${output}/desktop-preview.png` });
  await page.setViewportSize({ width: 390, height: 844 });
  await workspace.scrollIntoViewIfNeeded();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false, "mobile has no page-wide horizontal overflow");
  await page.screenshot({ path: `${output}/mobile-evidence.png` });
  const confirm = page.locator("#confirm-assessment");
  await confirm.getByLabel("Confirmation", { exact: true }).fill("APPROVE & PROCESS");
  await confirm.getByRole("button", { name: "Approve & Process", exact: true }).click();
  await page.locator("#rights-workspace").getByRole("heading", { name: "Documented authorisation" }).waitFor();
  await Promise.all(app.pipeline.inflight.values());
  assert.equal(app.pipeline.status(feedUrl, "owned-one").state, "READY");
  assert.equal(providerCalls(), 1, "only the bounded mocked job ran");
  app.intelligencePolicy.set({ feedUrl, episodeId: "owned-one", tier: "LOW", applyToFuture: false, reason: "Verify the saved episode automatic-preparation setting." });
  await page.getByRole("button", { name: "Open episode", exact: true }).first().click();
  await page.locator(".processing-status").getByRole("heading", { name: "READY", exact: true }).waitFor();
  assert.equal(await page.getByLabel("Allow this episode in automatic preparation", { exact: true }).isChecked(), false);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.locator(".processing-status").scrollIntoViewIfNeeded();
  await page.screenshot({ path: `${output}/desktop-ready.png` });
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ passed: true, desktop: 1440, mobile: 390, errors, mockProviderCalls: providerCalls(), paidCalls: 0, output }));
  await context.close();
} finally {
  await browser.close();
  await new Promise((resolve) => app.server.close(resolve));
  app.store.close();
}
