 store.set('intelligence','queued',{state:'QUEUED',updatedAt:at(-1000)});
 store.set('processing-event','budget',{state:'BLOCKED',code:'BUDGET_LIMIT',at:at(-1000)});
 store.set('processing-event','provider',{state:'FAILED',code:'PROVIDER_TIMEOUT',at:at(-1000)});
