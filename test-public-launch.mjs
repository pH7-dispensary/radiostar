 delivery.validation.features.brief.state='ANALYSING';delivery.topics.length=0;
 assert.equal(validatedDelivery(output,source).validation.complete,true);
 assert.equal(validatedDelivery(output,source).validation.features.brief.state,'READY');
 assert(validatedDelivery(output,source).topics.length>0,'request projection cannot poison cached validation');
 const changed=structuredClone(source);changed.segments[0].text='The only topic is a red bicycle.';
 assert.equal(validatedDelivery(output,changed).validation.complete,false,'changed source text invalidates evidence');
 changed.segments[0].id='different';assert.equal(validatedDelivery(output,changed).validation.complete,false);
 const changedOutput=structuredClone(output);changedOutput.chapters[0].endMs=60001;
 assert.equal(validatedDelivery(changedOutput,source).validation.features.chapters.state,'FAILED','changed timestamps invalidate validation');
 assert.equal(validatedDelivery({...output,validationFailures:[{feature:'brief',code:'REVIEW_FAILED'}]},source).validation.complete,false);
 assert.equal(validatedDelivery({...output,brief:{...output.brief,overview:'The guest recommends an unrelated imaginary medicine.'}},source).validation.complete,false);
 const index={fingerprint:'exact-source',segments:[{id:'segment'}]};
 const semantic={state:'READY',version:SEMANTIC_VERSION,fingerprint:index.fingerprint,cursor:1,total:1,rows:[{segmentId:'segment',vector:Array(DIMENSIONS).fill(.1)}]};
 semantic.checksum=semanticChecksum(semantic);store.set('semantic-index','episode',semantic);
 const invalid={...semantic,rows:[{segmentId:'segment',vector:Array(DIMENSIONS).fill(0)}]};
 assert.equal(semanticStatus(store,'episode',index).valid,true);
 assert.throws(()=>store.transaction(()=>{
  store.set('semantic-index','episode',invalid);
  assert.equal(semanticStatus(store,'episode',index).valid,false);
  throw Error('Rollback fixture');
 }),/Rollback fixture/);
 store.set('semantic-index','episode',semantic);
 assert.equal(semanticStatus(store,'episode',index).valid,true,'rolled-back revision cannot poison the next committed write');
 const projected=semanticStatus(store,'episode',index);projected.valid=false;
 assert.equal(semanticStatus(store,'episode',index).valid,true,'caller mutation cannot poison readiness');
 store.db.prepare("UPDATE records SET payload=? WHERE kind='semantic-index' AND id='episode'").run(JSON.stringify(invalid));
 assert.equal(semanticStatus(store,'episode',index).state,'FAILED','direct writes invalidate readiness immediately');
 store.set('semantic-index','episode',semantic);
 assert.equal(semanticStatus(store,'episode',index).valid,true);
 assert.equal(semanticStatus(store,'episode',{...index,segments:[{id:'changed-source'}]}).valid,false,'segment identity cannot reuse a prior verdict');
