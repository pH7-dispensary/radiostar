 for(const [id,kind,time] of [['bad','skipped_conversation',-1000],['good','good',-1000],['missed','missed',-1000],['old','skipped_conversation',-7200000],['future','skipped_conversation',1000]]) store.set('skip-feedback',id,{kind,createdAt:at(time),owner:'not-exported'});
